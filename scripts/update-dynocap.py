"""Update Formula/dynocap.rb from a complete dynocap GitHub release.

Set DYNOCAP_TAG to a stable tag (v1.2.3) to use that release. When it is unset,
the latest stable release is used. The formula file is replaced only after the
versioned archive and its checksum are present, so a partial release leaves it
untouched.

The install method must stay in step with packaging/homebrew/dynocap.rb in
baires/dynocap. There is no bottle: install re-signs the CLI on the Mac.
"""
import json
import os
import re
import urllib.error
import urllib.request
from pathlib import Path

FORMULA = Path("Formula/dynocap.rb")
TAG_RE = re.compile(r"v[0-9]+\.[0-9]+\.[0-9]+")
SHA_RE = re.compile(r"[0-9a-f]{64}")


def fail(message):
    raise SystemExit(message)


def fetch(url):
    token = os.environ.get("GH_TOKEN", "")
    if not token:
        fail("GH_TOKEN is required")
    request = urllib.request.Request(
        url,
        headers={
            "Authorization": "Bearer " + token,
            "Accept": "application/vnd.github+json",
            "User-Agent": "baires-homebrew-tap",
        },
    )
    try:
        with urllib.request.urlopen(request) as response:
            return response.read()
    except urllib.error.HTTPError as error:
        fail(f"GitHub request failed ({error.code}) for {url}")


def asset_name(tag):
    return f"dynocap-{tag}-darwin-arm64.tar.gz"


def release_api_url(tag):
    if tag:
        return f"https://api.github.com/repos/baires/dynocap/releases/tags/{tag}"
    return "https://api.github.com/repos/baires/dynocap/releases/latest"


def parse_checksum(text, name):
    lines = [line for line in text.splitlines() if line.strip()]
    if len(lines) != 1:
        fail("checksum file is incomplete or malformed")
    parts = lines[0].split()
    if len(parts) != 2 or not SHA_RE.fullmatch(parts[0]) or parts[1] != name:
        fail("checksum file is incomplete or malformed")
    return parts[0]


def require_assets(release, tag):
    assets = {asset["name"]: asset for asset in release.get("assets") or []}
    names = [asset_name(tag), asset_name(tag) + ".sha256"]
    missing = []
    for name in names:
        asset = assets.get(name)
        if asset is None or asset.get("state") != "uploaded" or not asset.get("size"):
            missing.append(name)
    if missing:
        fail("Release assets are incomplete: " + ", ".join(missing))
    return assets


def formula_text(tag, url, digest):
    lines = [
        "# Generated by scripts/update-dynocap.py from the dynocap release.",
        "# No bottle: install re-signs the CLI on the Mac that boots VMs.",
        "class Dynocap < Formula",
        '  desc "Local Linux microVM runtime for AI agents on macOS"',
        '  homepage "https://github.com/baires/dynocap"',
        f'  url "{url}"',
        f'  sha256 "{digest}"',
        '  license "Apache-2.0"',
        "",
        '  depends_on "e2fsprogs"',
        "  depends_on macos: :ventura",
        "",
        "  on_intel do",
        '    odie "DynoCap publishes Apple Silicon (darwin-arm64) only."',
        "  end",
        "",
        "  def install",
        "    if Hardware::CPU.intel?",
        '      odie "DynoCap publishes Apple Silicon (darwin-arm64) only."',
        "    end",
        '    prefix.install Dir["*"]',
        '    system "xattr", "-dr", "com.apple.quarantine", prefix',
        '    system "codesign", "--sign", "-",',
        '           "--entitlements", prefix/"entitlements/dynocap.entitlements",',
        '           "--force", prefix/"bin/dynocap"',
        "  end",
        "",
        "  def caveats",
        "    <<~EOS",
        "      Run `dynocap doctor --fix` in your project after install.",
        "      This formula re-signed the CLI with the bundled virtualization entitlement.",
        "      The first runtime preparation needs Go 1.22 or newer.",
        "    EOS",
        "  end",
        "",
        "  test do",
        '    assert_match "dynocap", shell_output("#{bin}/dynocap --version")',
        "  end",
        "end",
    ]
    expected = f"https://github.com/baires/dynocap/releases/download/{tag}/{asset_name(tag)}"
    if url != expected or not SHA_RE.fullmatch(digest):
        fail("Unexpected asset URL")
    return "\n".join(lines) + "\n"


def write_formula(content):
    temporary = FORMULA.with_suffix(".rb.tmp")
    try:
        temporary.write_text(content, encoding="utf-8")
        os.replace(temporary, FORMULA)
    finally:
        if temporary.exists():
            temporary.unlink()


def requested_tag():
    tag = os.environ.get("DYNOCAP_TAG", "").strip()
    if tag.startswith("refs/tags/"):
        tag = tag[len("refs/tags/") :]
    if tag and not TAG_RE.fullmatch(tag):
        fail("Expected a stable semantic version")
    return tag


def main():
    requested = requested_tag()
    try:
        release = json.loads(fetch(release_api_url(requested)))
    except json.JSONDecodeError:
        fail("GitHub release response was not valid JSON")
    tag = release.get("tag_name") or ""
    if requested and tag != requested:
        fail("Release tag does not match the requested tag")
    if not TAG_RE.fullmatch(tag):
        fail("Expected a stable semantic version")
    assets = require_assets(release, tag)
    name = asset_name(tag)
    url = assets[name].get("browser_download_url") or ""
    try:
        checksum = fetch(assets[name + ".sha256"]["browser_download_url"]).decode()
    except UnicodeDecodeError:
        fail("checksum file is incomplete or malformed")
    digest = parse_checksum(checksum, name)
    write_formula(formula_text(tag, url, digest))
    print(f"Updating formula for {tag}", flush=True)


if __name__ == "__main__":
    main()
